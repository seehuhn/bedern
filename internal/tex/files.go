// Family is the name of the font family in LaTeX, and the first part of the
// names of the files.
const Family = "bedern"

// Version is the version of the files for TeX.
const Version = "0.001"

// MapFile is the name of the map file.
const MapFile = Family + ".map"

// UnicodeFile is the name of the file which maps the glyphs to Unicode.
const UnicodeFile = Family + "-glyphtounicode.tex"

// A Font is one font of the family as TeX uses it.
type Font struct {
	Style design.Style

	// Series is the series of the font in LaTeX, m or b.
	Series string

	// Glyphs holds the glyphs of the font; the first is .notdef.
	Glyphs []glyphs.Glyph

	// Slant is the slant of the font as a ratio, which is zero for an
	// upright font.  A font with a slant is the outline file of an upright
	// font which the map file slants, with a metric file of its own.
	Slant float64
}

// SlantRatio is the slant of the slanted instances of the fonts, a ratio.
const SlantRatio = 1.0 / 6

// Slanted returns the slanted instances of the fonts which are upright, in the
// order of the fonts, with the slant SlantRatio.
func Slanted(fonts []*Font) []*Font {
	var out []*Font
	for _, f := range fonts {
		if f.Slant == 0 {
			g := *f
			g.Slant = SlantRatio
			out = append(out, &g)
		}
	}
	return out
}

// Shape returns the shape of the font in LaTeX, n for an upright font and sl
// for a slanted one.
func (f *Font) Shape() string {
	if f.Slant != 0 {
		return "sl"
	}
	return "n"
}

// TFM returns the name of the metric file of the font in the encoding e,
// without the ending: the family, the style, sl for a slanted font and the
// encoding in lower case, joined by hyphens.
func (f *Font) TFM(e *Encoding) string {
	name := Family + "-" + strings.ToLower(f.Style.Subfamily)
	if f.Slant != 0 {
		name += "-sl"
	}
	return name + "-" + e.Tag()
}

// PFB returns the name of the file of the outlines.
func (f *Font) PFB() string { return f.Style.PostScript + ".pfb" }

// header returns the first lines of a generated file, each started by the
// comment sign: the name and purpose of the file, the copyright, and the
// notice of the LaTeX Project Public License, under which the files for TeX
// stand, with the list of the files of the work.
func header(comment, name, what string) string {
	var b strings.Builder
	line := func(format string, args ...any) {
		if format == "" {
			b.WriteString(comment + "\n")
			return
		}
		fmt.Fprintf(&b, "%s %s\n", comment, fmt.Sprintf(format, args...))
	}
	line("%s: %s", name, what)
	line("%s", bedern.Copyright)
	line("SPDX-License-Identifier: LPPL-1.3c")
	line("")
	line("This work may be distributed and/or modified under the")
	line("conditions of the LaTeX Project Public License, either version 1.3c")
	line("of this license or (at your option) any later version.")
	line("The latest version of this license is in")
	line("  %s", LPPLURL)
	line("and version 1.3c or later is part of all distributions of LaTeX")
	line("version 2008 or later.")
	line("")
	line("This work has the LPPL maintenance status \"maintained\".")
	line("The Current Maintainer of this work is Jochen Voss <voss@seehuhn.de>.")
	line("This work consists of the files %s.", strings.Join(workFiles(), ", "))
	line("The fonts of the family, in every format, are not part of this work;")
	line("they are released under the SIL Open Font License, see OFL.txt.")
	line("")
	line("This file is generated by the command bedern.")
	return b.String()
}

// LPPLURL is the address of the text of the LaTeX Project Public License.
const LPPLURL = "https://www.latex-project.org/lppl.txt"

// workFiles returns the names of the files which stand under the LaTeX
// Project Public License.
func workFiles() []string {
	files := []string{Family + ".sty", PlainFile, UnicodeFile}
	for _, e := range Encodings {
		files = append(files, FDFile(e))
	}
	for _, e := range Encodings {
		files = append(files, e.EncFile())
	}
	return append(files, MapFile)
}

// EncFile returns the encoding file of e for the glyphs gs: the vector of
// the 256 glyph names, with .notdef for a position without a glyph.
func EncFile(e *Encoding, gs []glyphs.Glyph) []byte {
	index, _ := e.Resolve(gs)
	var b strings.Builder
	b.WriteString(header("%", e.EncFile(), "the encoding "+e.Name+" for the Bedern fonts"))
	fmt.Fprintf(&b, "/%s [\n", e.VectorName())
	for c, i := range index {
		name := ".notdef"
		if i >= 0 {
			name = gs[i].Name
		}
		b.WriteString("/" + name)
		if c%8 == 7 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("] def\n")
	return []byte(b.String())
}

// Map returns the map file, which has one line for each font in each
// encoding.
func Map(fonts []*Font) []byte {
	var b strings.Builder
	b.WriteString(header("%", MapFile, "the fonts of the Bedern family for TeX"))
	for _, f := range fonts {
		for _, e := range Encodings {
			slant := ""
			if f.Slant != 0 {
				slant = fmt.Sprintf("%.4f SlantFont ", f.Slant)
			}
			fmt.Fprintf(&b, "%s %s \"%s%s ReEncodeFont\" <%s <%s\n",
				f.TFM(e), f.Style.PostScript, slant, e.VectorName(), e.EncFile(), f.PFB())
		}
	}
	return []byte(b.String())
}

// FDFile returns the name of the font definition file of the encoding e.
func FDFile(e *Encoding) string { return e.Tag() + Family + ".fd" }

// FD returns the font definition file of the encoding e: the family with one
// shape for each font, at every size, the shape it as a substitute for sl, and
// the series bx as a substitute for b.  The file of TS1 also declares which
// glyphs of TS1 the family has.
func FD(e *Encoding, fonts []*Font, now time.Time) []byte {
	var b strings.Builder
	name := FDFile(e)
	b.WriteString(header("%%", name, "the Bedern fonts in the encoding "+e.Name))
	fmt.Fprintf(&b, "\\ProvidesFile{%s}[%s v%s Font definitions for %s/%s]\n",
		name, now.Format("2006/01/02"), Version, e.Name, Family)
	fmt.Fprintf(&b, "\\DeclareFontFamily{%s}{%s}{}\n", e.Name, Family)
	bold := false
	slanted := make(map[string]bool)
	for _, f := range fonts {
		fmt.Fprintf(&b, "\\DeclareFontShape{%s}{%s}{%s}{%s}{<-> %s}{}\n",
			e.Name, Family, f.Series, f.Shape(), f.TFM(e))
		bold = bold || f.Series == "b"
		if f.Slant != 0 {
			slanted[f.Series] = true
		}
	}
	for _, f := range fonts {
		if f.Slant != 0 && slanted[f.Series] {
			fmt.Fprintf(&b, "\\DeclareFontShape{%s}{%s}{%s}{it}{<->ssub * %s/%s/sl}{}\n",
				e.Name, Family, f.Series, Family, f.Series)
		}
	}
	if bold {
		for _, shape := range []string{"n", "sl", "it"} {
			if shape == "n" || slanted["b"] {
				fmt.Fprintf(&b, "\\DeclareFontShape{%s}{%s}{bx}{%s}{<->ssub * %s/b/%s}{}\n",
					e.Name, Family, shape, Family, shape)
			}
		}
	}
	if e == TS1 {
		sub := 0
		for _, f := range fonts {
			sub = max(sub, TS1Subset(f.Glyphs))
		}
		fmt.Fprintf(&b, "\\DeclareEncodingSubset{TS1}{%s}{%d}\n", Family, sub)
	}
	b.WriteString("\\endinput\n")
	return []byte(b.String())
}

// ts1Levels gives the positions of TS1 which LaTeX uses only in a font whose
// subset of TS1 has a number below the level.  The positions which are not
// listed and which LaTeX tests have the level 2.
var ts1Levels = map[int]int{
	0x4F: 1,
	0x3C: 3, 0x3E: 3,
	0x18: 4, 0x19: 4, 0x5E: 4, 0x5F: 4, 0x8D: 4, 0x8E: 4, 0x92: 4, 0x96: 4,
	0x9B: 5, 0x9D: 5,
	0x8C: 6, 0xA4: 6,
	0x2F: 7, 0x3D: 7, 0x57: 7, 0xB5: 7,
	0x20: 8, 0xBF: 8,
	0xB2: 9, 0xB3: 9, 0xB9: 9,
}

// ts1Always lists the positions of TS1 which LaTeX uses in every font.
var ts1Always = map[int]bool{
	0x0D: true, 0x12: true, 0x17: true, 0x1F: true, 0x24: true, 0x27: true,
	0x2A: true, 0x2C: true, 0x2E: true, 0x84: true, 0x85: true, 0x87: true,
	0x88: true, 0x97: true, 0xA2: true, 0xA3: true, 0xA5: true, 0xA6: true,
	0xA7: true, 0xA9: true, 0xAA: true, 0xAC: true, 0xAE: true, 0xB0: true,
	0xB1: true, 0xB6: true, 0xB7: true, 0xBA: true, 0xBC: true, 0xBD: true,
	0xBE: true, 0xD6: true, 0xF6: true,
	// The following positions have no command in LaTeX.
	0x51: true, 0x71: true,
}

// TS1Subset returns the number of the subset of TS1 which LaTeX is told the
// glyphs gs have: the least number at which LaTeX uses no position of TS1
// for which gs has no glyph, from 0, when every position has a glyph, to 9.
func TS1Subset(gs []glyphs.Glyph) int {
	_, missing := TS1.Resolve(gs)
	sub := 0
	for _, c := range missing {
		if ts1Always[c] {
			continue
		}
		level, ok := ts1Levels[c]
		if !ok {
			level = 2
		}
		sub = max(sub, level)
	}
	return sub
}

// A puCommand is the command of a glyph in the Private Use Area which the
// font has: the command, the code point, and the encoding and the position at
// which pdfTeX finds the glyph.
type puCommand struct {
	cmd  string
	r    rune
	enc  string
	slot int
}

// privateUseCommands returns the commands of the glyphs of gs in the Private
// Use Area which stand in a position of T1 or TS1 and whose command starts
// with \text.
func privateUseCommands(gs []glyphs.Glyph) []puCommand {
	byRune := make(map[rune]int, len(gs))
	for i, g := range gs {
		if g.Rune != 0 {
			byRune[g.Rune] = i
		}
	}
	var out []puCommand
	for _, pu := range glyphs.PrivateUseTable() {
		i, ok := byRune[pu.Rune]
		if !ok || !strings.HasPrefix(pu.Command, `\text`) {
			continue
		}
	encodings:
		for _, e := range Encodings {
			index, _ := e.Resolve(gs)
			for c, j := range index {
				if j == i {
					out = append(out, puCommand{pu.Command, pu.Rune, e.Name, c})
					break encodings
				}
			}
		}
	}
	return out
}

// Package returns the LaTeX package bedern.sty.  Under LuaTeX and XeTeX the
// package loads the OpenType fonts through fontspec.  Under any other engine
// it selects the encoding T1 and makes Bedern the roman family, and when
// pdfTeX writes a PDF file it reads the map file and the mappings to Unicode.
// For every glyph of the first font in the Private Use Area which stands in
// T1 or TS1, the package declares the command of the glyph: under LuaTeX and
// XeTeX at the code point, under the other engines at the position, unless
// LaTeX has the command.
//
// The options lining, oldstyle, proportional and tabular choose the figures:
// under LuaTeX and XeTeX through the feature Numbers of fontspec; under the
// other engines the figures of the fonts are the lining and tabular ones, and
// the options oldstyle and proportional give a warning.  An option which the
// package does not know gives a warning.  The italic shape is the slanted
// one, which fontspec makes by slanting the outlines.
func Package(fonts []*Font, now time.Time) []byte {
	var b strings.Builder
	b.WriteString(header("%%", Family+".sty", "the Bedern fonts for LaTeX"))
	b.WriteString("\\NeedsTeXFormat{LaTeX2e}\n")
	fmt.Fprintf(&b, "\\ProvidesPackage{%s}[%s v%s The Bedern fonts]\n",
		Family, now.Format("2006/01/02"), Version)
	b.WriteString("\\newif\\ifbedern@opentype\n")
	b.WriteString("\\def\\bedern@numbers{}\\def\\bedern@lacking{}\n")
	for _, o := range []struct{ name, value string }{
		{"lining", "Lining"}, {"tabular", "Monospaced"},
		{"oldstyle", "OldStyle"}, {"proportional", "Proportional"},
	} {
		fmt.Fprintf(&b, "\\DeclareOption{%s}{\\edef\\bedern@numbers{\\bedern@numbers,Numbers=%s}", o.name, o.value)
		if o.name == "oldstyle" || o.name == "proportional" {
			fmt.Fprintf(&b, "\\edef\\bedern@lacking{\\bedern@lacking\\space %s}", o.name)
		}
		b.WriteString("}\n")
	}
	fmt.Fprintf(&b, "\\DeclareOption*{\\PackageWarning{%s}{Unknown option `\\CurrentOption'}}\n", Family)
	b.WriteString("\\ProcessOptions\\relax\n")
	b.WriteString("\\ifdefined\\directlua\\bedern@opentypetrue\\fi\n")
	b.WriteString("\\ifdefined\\XeTeXversion\\bedern@opentypetrue\\fi\n")
	b.WriteString("\\ifbedern@opentype\n")
	b.WriteString("  \\RequirePackage{fontspec}\n")
	commands := privateUseCommands(fonts[0].Glyphs)
	var regular, bold string
	for _, f := range fonts {
		if f.Slant != 0 {
			continue
		}
		switch f.Series {
		case "m":
			regular = f.Style.PostScript
		case "b":
			bold = f.Style.PostScript
		}
	}
	slant := fmt.Sprintf("{FakeSlant=%.4f}", SlantRatio)
	fmt.Fprintf(&b, "  \\edef\\bedern@do{\\noexpand\\setmainfont{%s}[Extension=.otf,UprightFont=*,ItalicFont=*,ItalicFeatures=%s", regular, slant)
	if bold != "" {
		fmt.Fprintf(&b, ",BoldFont=%s,BoldItalicFont=%s,BoldItalicFeatures=%s", bold, bold, slant)
	}
	b.WriteString("\\bedern@numbers]}\\bedern@do\n")
	for _, c := range commands {
		fmt.Fprintf(&b, "  \\DeclareTextSymbol{%s}{TU}{\"%04X}\n", c.cmd, c.r)
	}
	b.WriteString("\\else\n")
	b.WriteString("  \\ifx\\bedern@lacking\\@empty\\else\n")
	fmt.Fprintf(&b, "    \\PackageWarning{%s}{The options\\bedern@lacking\\space have no effect under pdfTeX}\n", Family)
	b.WriteString("  \\fi\n")
	b.WriteString("  \\RequirePackage[T1]{fontenc}\n")
	b.WriteString("  \\RequirePackage{textcomp}\n")
	b.WriteString("  \\ifdefined\\pdfoutput\\ifnum\\pdfoutput>0\n")
	fmt.Fprintf(&b, "    \\pdfmapfile{=%s}\n", MapFile)
	fmt.Fprintf(&b, "    \\input{%s}\n", UnicodeFile)
	b.WriteString("    \\pdfgentounicode=1\n")
	b.WriteString("  \\fi\\fi\n")
	fmt.Fprintf(&b, "  \\renewcommand{\\rmdefault}{%s}\n", Family)
	for _, c := range commands {
		fmt.Fprintf(&b, "  \\ifdefined%s\\else\n", c.cmd)
		fmt.Fprintf(&b, "    \\DeclareTextSymbol{%s}{%s}{%d}\n", c.cmd, c.enc, c.slot)
		fmt.Fprintf(&b, "    \\DeclareTextSymbolDefault{%s}{%s}\n", c.cmd, c.enc)
		b.WriteString("  \\fi\n")
	}
	b.WriteString("\\fi\n")
	b.WriteString("\\endinput\n")
	return []byte(b.String())
}

// nameRune returns the code point which the glyph named name stands for: that
// of the glyph of the list with the name, or the code point which a name of
// the form uniXXXX (four hexadecimal digits) or uXXXX to uXXXXXX (four to six)
// gives.  It returns 0 if there is none.
func nameRune(gs []glyphs.Glyph, byName map[string]int, name string) rune {
	if j, ok := byName[name]; ok && gs[j].Rune != 0 {
		return gs[j].Rune
	}
	digits := ""
	switch {
	case strings.HasPrefix(name, "uni") && len(name) == 7:
		digits = name[3:]
	case strings.HasPrefix(name, "u") && len(name) >= 5 && len(name) <= 7:
		digits = name[1:]
	}
	if digits == "" || strings.ToUpper(digits) != digits {
		return 0
	}
	v, err := strconv.ParseUint(digits, 16, 32)
	if err != nil || v == 0 || v > 0x10FFFF || (v >= 0xD800 && v < 0xE000) {
		return 0
	}
	return rune(v)
}

// formBases names the glyph of the character for a base name of a form which
// is not the name of a glyph.
var formBases = map[string]string{"hyphendbl": "uni2E40"}

// unicodeOf returns the code points for which the glyph with the index i
// stands in copied text: its code point, the code points of the letters of a
// ligature, or the code point of the glyph whose name is the part of the
// name before the first full stop (a form of a character, which may have a
// code point in the Private Use Area of its own, copies out as the character),
// or its own code point.  Names of the forms uniXXXX and uXXXX
// stand for their code point.  It returns nil if there is none.
func unicodeOf(gs []glyphs.Glyph, byName map[string]int, i int) []rune {
	g := gs[i]
	if len(g.Parts) > 0 {
		var rs []rune
		for _, part := range g.Parts {
			r := nameRune(gs, byName, part)
			if r == 0 {
				return nil
			}
			rs = append(rs, r)
		}
		return rs
	}
	if base, _, ok := strings.Cut(g.Name, "."); ok {
		if alias, ok := formBases[base]; ok {
			base = alias
		}
		if r := nameRune(gs, byName, base); r != 0 {
			return []rune{r}
		}
	}
	if g.Rune != 0 {
		return []rune{g.Rune}
	}
	if strings.Contains(g.Name, "_") {
		var rs []rune
		for _, part := range strings.Split(g.Name, "_") {
			r := nameRune(gs, byName, part)
			if r == 0 {
				return nil
			}
			rs = append(rs, r)
		}
		return rs
	}
	return nil
}

// GlyphToUnicode returns the file which gives pdfTeX, for every glyph of
// every font in every encoding, the code points of the glyph.
func GlyphToUnicode(fonts []*Font) []byte {
	var b strings.Builder
	b.WriteString(header("%", UnicodeFile, "the code points of the glyphs of the Bedern fonts"))
	for _, f := range fonts {
		byName := make(map[string]int, len(f.Glyphs))
		for i, g := range f.Glyphs {
			byName[g.Name] = i
		}
		for _, e := range Encodings {
			index, _ := e.Resolve(f.Glyphs)
			seen := make(map[int]bool)
			names := make(map[string]bool)
			for _, i := range index {
				if i >= 0 {
					names[f.Glyphs[i].Name] = true
				}
			}
			for _, i := range index {
				if i < 0 || seen[i] {
					continue
				}
				seen[i] = true
				rs := unicodeOf(f.Glyphs, byName, i)
				if rs == nil {
					continue
				}
				var codes []string
				for _, r := range rs {
					codes = append(codes, fmt.Sprintf("%04X", r))
				}
				fmt.Fprintf(&b, "\\pdfglyphtounicode{tfm:%s/%s}{%s}\n",
					f.TFM(e), f.Glyphs[i].Name, strings.Join(codes, " "))
				// pdfTeX takes the name of a form without its suffix before it
				// looks for the glyph, so that the base has to be a key too, unless
				// it is the name of another glyph of the encoding
				if base, _, ok := strings.Cut(f.Glyphs[i].Name, "."); ok && base != "" && !names[base] {
					names[base] = true
					fmt.Fprintf(&b, "\\pdfglyphtounicode{tfm:%s/%s}{%s}\n",
						f.TFM(e), base, strings.Join(codes, " "))
				}
			}
		}
	}
	b.WriteString("\\endinput\n")
	return []byte(b.String())
}

