// t1Case returns the positions of T1 which hold the lowercase and the
// uppercase form of the letter at the position c, and false if the position
// holds no letter.
func t1Case(slotOf map[rune]int, c int) (lower, upper int, ok bool) {
	r := T1.Slots[c].Rune
	switch c {
	case 0xDF: // the two letters S
		return 0xFF, 0xDF, true
	case 0xFF: // ß
		return 0xFF, 0xDF, true
	case 0x9E: // đ
		return 0x9E, 0xD0, true
	case 0x1A: // the dotless j
		return 0x1A, 'J', true
	case 0x7F, 0x17:
		return 0, 0, false
	}
	if !unicode.IsLetter(r) || (r >= 0xFB00 && r <= 0xFB06) {
		return 0, 0, false
	}
	lower, okL := slotOf[unicode.ToLower(r)]
	upper, okU := slotOf[unicode.ToUpper(r)]
	if !okL {
		lower = c
	}
	if !okU {
		upper = c
	}
	return lower, upper, true
}

// PlainFile is the name of the macro file for plain TeX.
const PlainFile = Family + ".tex"

// TypewriterFont is the metric file of the typewriter font of plain TeX, a
// font of T1 of the EC fonts, which the file of macros names and which the
// fonts of the TeX installation provide.
const TypewriterFont = "ectt1000"

// Plain returns the macro file for plain TeX.  The file reads the map file
// and the mappings to Unicode when pdfTeX writes a PDF file, loads the fonts
// in the encoding T1 at 10 pt as the fonts of \rm, \bf, \sl and \it (the
// slanted font stands for the italic) and \tt (the typewriter font), makes
// them the fonts \tenrm, \tenbf, \tensl, \tenit and \tentt, so that the
// footline and every other command of plain TeX which names them uses them,
// and defines the commands of the accents and of the special letters, the
// lowercase codes and the uppercase codes for T1.
// An accent command with a letter which T1 holds with that accent gives the
// character of T1, and the accent is set over the letter otherwise.
func Plain(fonts []*Font) []byte {
	var b strings.Builder
	b.WriteString(header("%", PlainFile, "the Bedern fonts in the encoding T1 for plain TeX"))
	b.WriteString("\\ifx\\pdfoutput\\undefined\\else\\ifnum\\pdfoutput>0\n")
	fmt.Fprintf(&b, "  \\pdfmapfile{=%s}\n", MapFile)
	fmt.Fprintf(&b, "  \\input %s\n", UnicodeFile)
	b.WriteString("  \\pdfgentounicode=1\n")
	b.WriteString("\\fi\\fi\n")
	b.WriteString("\\catcode`\\@=11\n")
	for _, f := range fonts {
		cmd := "rm"
		switch {
		case f.Series == "b" && f.Slant == 0:
			cmd = "bf"
		case f.Series == "m" && f.Slant != 0:
			cmd = "sl"
		case f.Slant != 0 || f.Series != "m":
			continue
		}
		fmt.Fprintf(&b, "\\font\\bedern%s=%s\n", cmd, f.TFM(T1))
		fmt.Fprintf(&b, "\\let\\ten%s=\\bedern%s\n", cmd, cmd)
		switch cmd {
		case "rm":
			b.WriteString("\\def\\rm{\\fam\\z@\\bedernrm}\n")
		case "bf":
			b.WriteString("\\def\\bf{\\fam\\bffam\\bedernbf}\n")
		case "sl":
			b.WriteString("\\let\\tenit=\\bedernsl\n")
			b.WriteString("\\def\\sl{\\fam\\slfam\\bedernsl}\n")
			b.WriteString("\\def\\it{\\fam\\itfam\\bedernsl}\n")
		}
	}
	fmt.Fprintf(&b, "\\font\\bedernttfont=%s\n", TypewriterFont)
	b.WriteString("\\let\\tentt=\\bedernttfont\n")
	b.WriteString("\\def\\tt{\\fam\\ttfam\\bedernttfont}\n")
	for _, l := range plainLetters {
		fmt.Fprintf(&b, "\\chardef\\%s=\"%02X\n", l.cmd, l.slot)
	}
	b.WriteString("\\def\\bedern@acc#1#2{\\expandafter\\ifx\\csname bedern@#1@\\string#2\\endcsname\\relax\n")
	b.WriteString("  {\\accent#1 #2}\\else\\csname bedern@#1@\\string#2\\endcsname\\fi}\n")
	b.WriteString("\\def\\bedern@low#1#2#3{\\leavevmode\\expandafter\\ifx\\csname bedern@#1@\\string#3\\endcsname\\relax\n")
	b.WriteString("  {\\ooalign{\\null#3\\crcr\\hidewidth\\char#1#2}}\\else\\csname bedern@#1@\\string#3\\endcsname\\fi}\n")
	b.WriteString("\\def\\bedern@def#1#2#3{\\expandafter\\chardef\\csname bedern@#1@#2\\endcsname=#3\\relax}\n")
	for _, a := range plainAccents {
		switch a.slot {
		case 0x0B:
			fmt.Fprintf(&b, "\\def\\%s#1{\\bedern@low{%d}{\\hidewidth}{#1}}\n", a.cmd, a.slot)
		case 0x0C:
			fmt.Fprintf(&b, "\\def\\%s#1{\\bedern@low{%d}{}{#1}}\n", a.cmd, a.slot)
		default:
			fmt.Fprintf(&b, "\\def\\%s#1{\\bedern@acc{%d}{#1}}\n", a.cmd, a.slot)
		}
	}
	b.WriteString("\\def\\b#1{\\oalign{#1\\crcr\\hidewidth\\vbox to.2ex{\\hbox{\\char9}\\vss}\\hidewidth}}\n")
	slotOf := make(map[rune]int)
	for c := 255; c >= 0; c-- {
		if r := T1.Slots[c].Rune; r != 0 {
			slotOf[r] = c
		}
	}
	accentOf := make(map[rune]int)
	for _, a := range plainAccents {
		accentOf[a.mark] = a.slot
	}
	type entry struct {
		accent int
		key    string
		slot   int
	}
	var entries []entry
	for c := 0x80; c < 256; c++ {
		r := T1.Slots[c].Rune
		if r == 0 {
			continue
		}
		d := []rune(norm.NFD.String(string(r)))
		if len(d) != 2 {
			continue
		}
		accent, ok := accentOf[d[1]]
		if !ok {
			continue
		}
		entries = append(entries, entry{accent, string(d[0]), c})
		if d[0] == 'i' || d[0] == 'j' {
			entries = append(entries, entry{accent, "\\string\\" + string(d[0]), c})
		}
	}
	sort.SliceStable(entries, func(i, j int) bool {
		if entries[i].accent != entries[j].accent {
			return entries[i].accent < entries[j].accent
		}
		return entries[i].slot < entries[j].slot
	})
	seen := make(map[string]bool)
	for _, e := range entries {
		key := fmt.Sprintf("%d@%s", e.accent, e.key)
		if seen[key] {
			continue
		}
		seen[key] = true
		fmt.Fprintf(&b, "\\bedern@def{%d}{%s}{\"%02X}\n", e.accent, e.key, e.slot)
	}
	for c := 0; c < 256; c++ {
		if c >= 0x21 && c <= 0x7E {
			continue
		}
		lower, upper, ok := t1Case(slotOf, c)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "\\lccode\"%02X=\"%02X \\uccode\"%02X=\"%02X\n", c, lower, c, upper)
	}
	b.WriteString("\\catcode`\\@=12\n")
	b.WriteString("\\rm\n")
	b.WriteString("\\endinput\n")
	return []byte(b.String())
}
