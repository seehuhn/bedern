// The fit of the side spaces.
//
// The table fitTable (fit_table.go) gives for every glyph which is not
// composed its two side spaces, measured horizontally in the italic from the
// edges of the advance to the leftmost and the rightmost ink of the band of
// the glyph: from the baseline to the x-height for the lowercase, to the cap
// height for the others, and the whole ink where the band has none.  A shear
// about the baseline moves both edges of the white at one height by the same
// amount, so that these distances are those of the upright description.  The
// table describes the glyphs as sides, not as changes of the drawing: the
// assembly moves each glyph so that its left side is that of the table and
// sets its advance from the right side.

// Sides are the side spaces of a glyph.
type Sides struct{ Left, Right float64 }

// band returns the heights between which the sides of a glyph are measured.
func band(name string, r rune) (lo, hi float64) {
	rp := design.Regular()
	if r >= 'a' && r <= 'z' || name == "dotlessi" || name == "uni0237" {
		return 0, rp.XHeight
	}
	return 0, rp.CapHeight
}

// sidesOf returns the sides of the glyph as it stands, and false for a glyph
// without ink.
func sidesOf(g glyphs.Glyph) (Sides, bool) {
	if len(g.Path) == 0 {
		return Sides{}, false
	}
	lo, hi := band(g.Name, g.Rune)
	x0, x1 := inkSpan(g.Path, lo, hi)
	if math.IsInf(x0, 0) {
		x0, _, x1, _ = g.Path.BBox()
	}
	return Sides{x0, g.Advance - x1}, true
}

// fitted returns the glyph moved and with the advance which give it the
// sides s.
func fitted(g glyphs.Glyph, s Sides) glyphs.Glyph {
	now, ok := sidesOf(g)
	if !ok {
		return g
	}
	dx := math.Round(s.Left - now.Left)
	g.Path = moved(g.Path, dx, 0)
	g.Advance = math.Round(g.Advance + dx + s.Right - now.Right)
	return g
}

// Sidings returns the sides of the bases as the table would have them for
// the glyphs as they are built with p (with or without the fit), by
// name.
func Sidings(p Params) (map[string]Sides, error) {
	gs, err := bases(p)
	if err != nil {
		return nil, err
	}
	if p.Fit {
		for i := range gs {
			if s, ok := fitTable[gs[i].Name]; ok {
				gs[i] = fitted(gs[i], s)
			}
		}
	}
	out := map[string]Sides{}
	for _, g := range gs {
		if s, ok := sidesOf(g); ok {
			out[g.Name] = Sides{math.Round(s.Left), math.Round(s.Right)}
		}
	}
	return out, nil
}

// WriteTable writes the Go source of the fit table with the given sides.
func WriteTable(w io.Writer, sides map[string]Sides) error {
	names := make([]string, 0, len(sides))
	for n := range sides {
		names = append(names, n)
	}
	slices.Sort(names)
	if _, err := fmt.Fprint(w, `// Copyright 2026 Jochen Voss <voss@seehuhn.de>
// SPDX-License-Identifier: OFL-1.1

// Code generated by go run ./cmd/italicfont -write-fit; DO NOT EDIT.

package assembly

// fitTable gives the side spaces of the glyphs which are not composed (fit.go).
var fitTable = map[string]Sides{
`); err != nil {
		return err
	}
	for _, n := range names {
		s := sides[n]
		if _, err := fmt.Fprintf(w, "\t%q: {%g, %g},\n", n, s.Left, s.Right); err != nil {
			return err
		}
	}
	_, err := fmt.Fprint(w, "}\n")
	return err
}

// ItalicCorrection returns the italic correction of the glyph: the rightmost
// ink above half its height (half the x-height for the lowercase letters
// without ascender, half the cap height for the others) less the advance,
// plus pad, and zero where that is negative.
func ItalicCorrection(g glyphs.Glyph, pad float64) float64 {
	if len(g.Path) == 0 {
		return 0
	}
	rp := design.Regular()
	h := rp.CapHeight
	if _, _, _, top := g.Path.BBox(); top < rp.XHeight+40 {
		h = rp.XHeight
	}
	_, x1 := inkSpan(g.Path, h/2, 2*rp.CapHeight)
	return math.Max(0, math.Round(x1-g.Advance+pad))
}

// WriteGlyphTable writes for every glyph its name, group, advance, sides and
// italic correction (with the pad of 10).
func WriteGlyphTable(w io.Writer, gs []glyphs.Glyph) error {
	for _, g := range gs {
		s, _ := sidesOf(g)
		if _, err := fmt.Fprintf(w, "%-16s %-8s %5.0f %6.0f %6.0f %4.0f\n", g.Name, kind(g), g.Advance, s.Left, s.Right, ItalicCorrection(g, 10)); err != nil {
			return err
		}
	}
	return nil
}
